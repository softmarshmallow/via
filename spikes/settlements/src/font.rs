/// Width in pixels of `text` at `scale`.
pub fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        n * (GLYPH_W as u32 + 1) * scale - scale
    }
}

pub fn text_height(scale: u32) -> u32 {
    GLYPH_H as u32 * scale
}

/// Draw `text` with its top-left at (x, y).
pub fn draw_text(img: &mut RgbImage, x: i32, y: i32, text: &str, scale: u32, color: [u8; 3]) {
    let mut cx = x;
    for ch in text.chars() {
        if let Some(g) = glyph(ch) {
            for (row, line) in g.iter().enumerate() {
                for (col, c) in line.chars().enumerate() {
                    if c != '#' {
                        continue;
                    }
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = cx + (col as u32 * scale + sx) as i32;
                            let py = y + (row as u32 * scale + sy) as i32;
                            if px >= 0
                                && py >= 0
                                && (px as u32) < img.width()
                                && (py as u32) < img.height()
                            {
                                img.put_pixel(px as u32, py as u32, Rgb(color));
                            }
                        }
                    }
                }
            }
        }
        cx += ((GLYPH_W as u32 + 1) * scale) as i32;
    }
}

/// Draw text with a contrasting halo, for labels over busy maps.
pub fn draw_text_halo(
    img: &mut RgbImage,
    x: i32,
    y: i32,
    text: &str,
    scale: u32,
    color: [u8; 3],
    halo: [u8; 3],
) {
    for dy in -1i32..=1 {
        for dx in -1i32..=1 {
            if dx != 0 || dy != 0 {
                draw_text(img, x + dx, y + dy, text, scale, halo);
            }
        }
    }
    draw_text(img, x, y, text, scale, color);
}
