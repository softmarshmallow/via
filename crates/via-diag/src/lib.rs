//! Diagnostics.
//!
//! Responsibility: the diagnostic record, which the code cannot construct without a code, a
//! subject, a location and a hint; the registry of core codes and the constants generated from
//! it; and the `diagnostics.json` document. Errors are values that say what to change, so every
//! crate above this one returns these rather than panicking.
//!
//! Governed by `spec/diagnostics.md`.
//!
//! # How a diagnostic travels
//!
//! 1. **Construction** ([`Diag::new`]): a node names a generated code constant from [`codes`], a
//!    [`Subject`], a [`Site`], a message and a hint. All five are arguments of the one
//!    constructor, so a diagnostic without them does not compile; message and hint are [`Text`],
//!    which cannot be blank. A `Diag` holds no file or line, because it is stored with its node's
//!    value and replayed (`spec/graph.md` 3.4).
//! 2. **Emission** ([`Diag::emit`]): the site is resolved against the current merge through
//!    [`Resolve`] to one [`Location`] and a chain, giving a [`Record`]. A site that does not
//!    resolve becomes `diag.internal`.
//! 3. **Finishing** ([`finish`]): once, `--fail-on`, aggregation and the total order of section 5.
//! 4. **Writing**: [`document`] gives `diagnostics.json` and the `--json` document;
//!    [`terminal::render`] the standard-error text; [`exit_status`] the exit status.
//!
//! A step's diagnostics enter through [`step::arrive`] (section 6); `via explain` is
//! [`explain`]; skipped dependents are [`poison`].

